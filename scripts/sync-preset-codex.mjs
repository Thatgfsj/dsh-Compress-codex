#!/usr/bin/env node
/**
 * Generate a preset overlay that runs this plugin inside an agent preset.
 *
 * Why this exists: an agent preset composes its own isolated services
 * (isolate: { compaction: true }), and loader patches address TOP-LEVEL entry
 * ids only. Patching "- id: compaction" fails with entry "compaction" not found,
 * because that group lives inside preset-<base>.config.plugins. The preset
 * registry has no extends/inheritance, so the roster must be restated verbatim.
 * That copy can drift when @deepseek-ai/dsh-web-app changes the source preset,
 * which is why this script exists: re-run it after an upgrade and diff.
 *
 * Usage:
 *   node scripts/sync-preset-codex.mjs --profile web --base standard --out out.yml
 */
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"

function arg(name, fallback) {
  const i = process.argv.indexOf("--" + name)
  return i === -1 ? fallback : process.argv[i + 1]
}

const profile = arg("profile", "web")
const base = arg("base", "standard")
const out = arg("out", "preset-codex.patch.yml")
const plugin = arg("plugin", "dsh-compress-codex")

const dump = execFileSync("dsh", ["--profile", profile, "--dump-config"], {
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024
})
const lines = dump.split(/\r?\n/)

const start = lines.findIndex((l) => l === "- id: preset-" + base)
if (start === -1) throw new Error("preset-" + base + " not found in the composed tree")
let end = lines.length
for (let i = start + 1; i < lines.length; i += 1) {
  if (/^- /.test(lines[i])) { end = i; break }
}
const pluginsAt = lines.findIndex((l, i) => i > start && i < end && l.trim() === "plugins:")
if (pluginsAt === -1) throw new Error("plugins: list not found inside preset-" + base)
const roster = lines.slice(pluginsAt, end)

// Retarget only the isolated compaction group. command-compact stays: it is
// backend-independent and follows whatever ctx.compaction the group provides.
const srcName = "name: \u0027@deepseek-ai/dsh-compaction-basic\u0027"
let retargeted = 0
const body = roster.map((line) => {
  if (line.trim() === "- id: compaction-basic") {
    retargeted += 1
    return line.replace("compaction-basic", "compaction-codex")
  }
  if (line.trim() === srcName) return line.replace(srcName, "name: " + plugin)
  return line
})
if (retargeted !== 1) {
  throw new Error("expected exactly one nested compaction-basic row, found " + retargeted)
}

// Re-indent by +4 so the roster sits under insert -> entry -> config.
const nested = body.map((l) => (l.trim() === "" ? l : "    " + l))

const header = [
  "# preset-codex -- a copy of the shipped \u0022" + base + "\u0022 preset whose isolated",
  "# compaction group runs " + plugin + " instead of the official backend.",
  "#",
  "# Generated by scripts/sync-preset-codex.mjs. Do not hand-edit: re-run the script",
  "# after upgrading @deepseek-ai/dsh-web-app and review the diff."
]
const tail = [
  "- insert:",
  "    - id: preset-codex",
  "      name: \u0027@deepseek-ai/dsh-agent-preset\u0027",
  "      config:",
  "        id: \u0027codex\u0027",
  "        order: 0"
]
const doc = header.concat(tail, nested, [""]).join("\n")

writeFileSync(out, doc)
console.log("sync-preset-codex: wrote " + out)
console.log("sync-preset-codex: retargeted rows = " + retargeted)
console.log("sync-preset-codex: source span lines = " + (end - pluginsAt))
