/**
 * D4 — summarization policy (docs/PLAN.md §1.3, issue #6).
 *
 * Two jobs live here, both owned by this module (docs/design-m1-m2.md §2.1):
 *
 *   1. build the instruction the summarizer model is called with. The baseline
 *      is Codex's `prompts/templates/compact/prompt.md` kept verbatim; the two
 *      extra fields this project exists for ("files touched", "known pitfalls")
 *      are inserted between bullet 4 and the closing line
 *      (docs/codex-impl-checklist.md §3.1-§3.2).
 *   2. project the model's reply down to pure text blocks — C5: reasoning and
 *      tool calls must never reach the checkpoint (checklist §3.3).
 *
 * Where the continuation semantics live: the outer shape of the replacement
 * message (`<compacted-summary>` + compactCheckpointSource) is generated by the
 * inherited transaction and is not ours to change (design-m1-m2.md §3, D5).
 * Codex's "another model already worked on this" preface therefore goes into the
 * *projected body*, exactly where Codex puts it (`SUMMARY_PREFIX + "\n" + body`,
 * codex-notes.md §3.4/§4) — never into the request template.
 *
 * The body semantics of #8 (injection) therefore land here, in this module; what
 * is left for #11 is to verify that the base transaction really produces that
 * outer frame — not to re-implement the preface.
 *
 * Zero dependencies on purpose (see config.js).
 */

/** Template ids this module can build. Issue #9 measures drift against them. */
export const SUMMARY_TEMPLATE_VERSIONS = Object.freeze(['codex-v1'])

/** The template version emitted when the policy does not name another one. */
export const SUMMARY_TEMPLATE_VERSION = SUMMARY_TEMPLATE_VERSIONS[0]

/** Codex `compact/prompt.md` line 1, verbatim (docs/codex-notes.md §3.2). */
const ROLE_INSTRUCTION =
  'You are performing a CONTEXT CHECKPOINT COMPACTION. Create a handoff summary for another LLM that will ' +
  'resume the task.'

/** Codex `compact/prompt.md` line 9, verbatim; always the last line of the prompt. */
const CLOSING_LINE =
  'Be concise, structured, and focused on helping the next LLM seamlessly continue the work.'

/**
 * Codex's four bullets, verbatim and in source order (codex-notes.md §3.2).
 *
 * The `id`s are ours: #9 and the tests address fields without matching prose.
 */
export const CODEX_SUMMARY_FIELDS = Object.freeze([
  Object.freeze({ id: 'progress', bullet: 'Current progress and key decisions made' }),
  Object.freeze({ id: 'context', bullet: 'Important context, constraints, or user preferences' }),
  Object.freeze({ id: 'next-steps', bullet: 'What remains to be done (clear next steps)' }),
  Object.freeze({
    id: 'references',
    bullet: 'Any critical data, examples, or references needed to continue'
  })
])

/**
 * The two fields Codex does not have — the reason this project exists
 * (codex-notes.md §3.3, "与议题 #6 期望字段的差距").
 *
 * Keyed by the ids accepted in `policy.summaryExtraFields`; the key order is the
 * canonical output order, so a caller cannot reorder the template by accident.
 * "(omit if none)" is our guard for the "no empty-shell fields" requirement:
 * Codex's own template has no missing-field policy at all.
 */
export const EXTRA_SUMMARY_FIELDS = Object.freeze({
  files: Object.freeze({
    id: 'files',
    bullet: 'Files touched and their current state (omit if none)'
  }),
  pitfalls: Object.freeze({
    id: 'pitfalls',
    bullet: 'Known pitfalls or failed approaches (omit if none)'
  })
})

/** Canonical order of the optional fields; also the closed set of accepted ids. */
export const EXTRA_SUMMARY_FIELD_IDS = Object.freeze(Object.keys(EXTRA_SUMMARY_FIELDS))

/**
 * Codex `templates/compact/summary_prefix.md`, verbatim (one line, no trailing
 * newline — Codex joins it as `format!("{SUMMARY_PREFIX}\n{summary}")`).
 *
 * It is a meta description addressed to the *next* model, not part of the
 * summarizer prompt, so the projection applies it and the template never does.
 */
export const SUMMARY_PREFIX =
  'Another language model started to solve this problem and produced a summary of its thinking process. ' +
  'You also have access to the state of the tools that were used by that language model. ' +
  'Use this to build on the work that has already been done and avoid duplicating work. ' +
  'Here is the summary produced by the other language model, use the information in this summary to ' +
  'assist with your own analysis:'

/**
 * Resolve `policy.summaryExtraFields` into the extra fields to render.
 *
 * Absent means "both": the documented default is all extras on. Absent is also
 * the state of a policy projected by the current normalizePolicy(), whose key
 * list does not carry summaryExtraFields yet — so the default cannot depend on
 * #3 landing first.
 *
 * `[]` is meaningful: it degrades the template to the pure Codex field set.
 * Anything else fails fast instead of silently shrinking the handoff — a typo
 * must not be readable as a deliberate policy.
 *
 * @param policy - normalized policy, or anything else the caller passed.
 * @returns frozen extra-field descriptors in canonical order.
 * @throws {TypeError} when summaryExtraFields is present but malformed.
 */
export function resolveSummaryExtraFields(policy) {
  const raw = policy === null || typeof policy !== 'object' ? undefined : policy.summaryExtraFields
  if (raw === undefined || raw === null) {
    return Object.freeze(EXTRA_SUMMARY_FIELD_IDS.map((id) => EXTRA_SUMMARY_FIELDS[id]))
  }
  if (!Array.isArray(raw)) {
    throw new TypeError(
      'dsh-compress-codex: summaryExtraFields must be an array of ' + EXTRA_SUMMARY_FIELD_IDS.join('/')
    )
  }
  for (const id of raw) {
    if (!EXTRA_SUMMARY_FIELD_IDS.includes(id)) {
      throw new TypeError(
        'dsh-compress-codex: unknown summaryExtraFields entry ' + String(id) + '; expected one of ' +
          EXTRA_SUMMARY_FIELD_IDS.join(', ')
      )
    }
  }
  return Object.freeze(
    EXTRA_SUMMARY_FIELD_IDS.filter((id) => raw.includes(id)).map((id) => EXTRA_SUMMARY_FIELDS[id])
  )
}

/**
 * Full ordered field list: Codex's four, then the enabled extras.
 *
 * @param policy - normalized policy.
 * @returns frozen field descriptors in render order.
 */
export function resolveSummaryFields(policy) {
  return Object.freeze([...CODEX_SUMMARY_FIELDS, ...resolveSummaryExtraFields(policy)])
}

/**
 * Render the instruction.
 *
 * Codex's lines 1, 2, "Include:" and 9 are fixed, and the extras are appended
 * after bullet 4, so `summaryExtraFields: []` reproduces Codex byte for byte.
 */
function renderPrompt(fields) {
  return [
    ROLE_INSTRUCTION,
    '',
    'Include:',
    ...fields.map((field) => '- ' + field.bullet),
    '',
    CLOSING_LINE
  ].join('\n')
}

/**
 * Read the template id out of the policy.
 *
 * An unknown id throws instead of falling back to 'codex-v1': silently emitting
 * one template while the operator asked for another is exactly the drift #9 has
 * to measure.
 *
 * @param policy - normalized policy.
 * @returns a known template id.
 * @throws {TypeError} when summaryTemplate is set to anything this build cannot render.
 */
function resolveSummaryTemplate(policy) {
  const raw = policy === null || typeof policy !== 'object' ? undefined : policy.summaryTemplate
  if (raw === undefined || raw === null) return SUMMARY_TEMPLATE_VERSION
  if (typeof raw !== 'string' || !SUMMARY_TEMPLATE_VERSIONS.includes(raw)) {
    throw new TypeError(
      'dsh-compress-codex: unknown summaryTemplate ' + JSON.stringify(raw) + '; this build emits ' +
        SUMMARY_TEMPLATE_VERSIONS.join(', ')
    )
  }
  return raw
}

/**
 * Project a model reply onto the checkpoint body (C5).
 *
 * Only `type: 'text'` blocks survive: reasoning, tool calls, tool results and
 * images are dropped by construction, so a dirty reply can never smuggle a tool
 * call into a checkpoint. Blank text carries no information and would only
 * create the empty-shell fields #6 must avoid, so it is dropped too.
 *
 * The Codex preface is prepended here, at the head of the body, because the
 * envelope around the body belongs to the base transaction (module docstring).
 * A reply with no usable text returns `null` — never a placeholder, never a
 * preface-only shell — which the engine reads as "route this to
 * compaction/summary-error" instead of persisting an empty checkpoint.
 *
 * @param rawOutput - the model's ContentBlock[]; anything else is treated as an
 *   empty reply rather than crashing the transaction.
 * @returns `[{ type: 'text', text }]`, or `null` when nothing survives.
 */
export function projectSummaryOutput(rawOutput) {
  if (!Array.isArray(rawOutput)) return null
  const texts = []
  for (const block of rawOutput) {
    if (block === null || typeof block !== 'object') continue
    if (block.type !== 'text') continue
    if (typeof block.text !== 'string') continue
    if (block.text.trim().length === 0) continue
    texts.push(block.text)
  }
  if (texts.length === 0) return null
  return [{ type: 'text', text: SUMMARY_PREFIX + '\n' + texts.join('\n') }]
}

/**
 * Build the summarization request for the replayed region.
 *
 * Returns the frozen `{ prompt, projection }` contract of design-m1-m2.md §2.3,
 * plus the template id and the field list, so #9 can record what produced a
 * summary without parsing prompt prose. `prompt` is the instruction text: #7
 * appends it as the trailing user text of the replayed prefix (C4), which is
 * why the replay payload itself does not shape it.
 *
 * Hand-off to #7, stated so the two halves cannot drift: returning a request is
 * what stops lib/engine.js from delegating to the official summarizer, and until
 * #7 lands it makes the engine throw its REFUSE.summary guard instead — an
 * unprojected summary must never be persisted. #7 owns the rest of the call:
 * run `ctx.llm.stream({ purpose: 'compaction' })` with this prompt appended to
 * the replayed prefix, feed the raw reply through `projection`, and return
 * `{ summary, rawOutput, llmStreamCall: true, provider, model }`. `projection`
 * is a function, not already-projected blocks, precisely because the raw reply
 * does not exist until #7 makes that call — and `null` from it is the signal to
 * route the failure to compaction/summary-error rather than write a checkpoint.
 *
 * @param context - decision inputs supplied by the engine.
 * @param context.input - SummarizationInput (system head + shadowed region).
 * @param context.agent - live agent; #7 reads routing from it.
 * @param context.policy - normalized policy from normalizePolicy().
 * @returns frozen `{ prompt, projection, template, fields }` — the shape #6/#7
 *   implement.
 * @throws {TypeError} when the replay input is missing, or the policy carries an
 *   unknown template or malformed summaryExtraFields.
 */
export function buildSummaryRequest(context) {
  const input = context === undefined || context === null ? undefined : context.input
  if (input === null || typeof input !== 'object') {
    throw new TypeError('dsh-compress-codex: buildSummaryRequest requires the replay input')
  }
  const policy = context.policy
  const template = resolveSummaryTemplate(policy)
  const fields = resolveSummaryFields(policy)
  return Object.freeze({
    template,
    prompt: renderPrompt(fields),
    fields,
    projection: projectSummaryOutput
  })
}
